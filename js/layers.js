(() => {
'use strict';
const app = window.BelgianLidar, {map, $, report} = app;
const common = {maxZoom:22,updateWhenIdle:true,updateWhenZooming:false,keepBuffer:1};
const flCredit = 'Bron: <a href="https://www.vlaanderen.be/datavindplaats/catalogus/wmts-digitaal-hoogtemodel-vlaanderen">Digitaal Vlaanderen</a>';
const waCredit = '© <a href="https://geoportail.wallonie.be/catalogue/89b00953-efdb-449b-baec-1c8e7ce483b5.html">SPW · MNT 2021–2022 hillshade</a> · <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>';
const deCredit = '© GeoBasis-DE / <a href="https://www.bkg.bund.de">BKG</a> (2026) · <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>';
const nrwCredit = '<a href="https://www.bezreg-koeln.nrw.de/geobasis-nrw">Geobasis NRW</a> · <a href="https://www.govdata.de/dl-de/zero-2-0">dl-de/zero-2-0</a>';
const rlpCredit = '©GeoBasis-DE / <a href="https://www.lvermgeo.rlp.de">LVermGeoRP</a> 2026 · <a href="https://www.govdata.de/dl-de/by-2-0">dl-de/by-2-0</a> [Daten bearbeitet]';
const deBounds = [[47.27,5.86],[55.06,15.05]];
const nrwBounds = [[50.057798,5.593338],[52.799797,9.741582]];
const rlpBounds = [[48.897996,6.037773],[51.000893,8.617703]];
// WMS 1.3.0 + EPSG:3857 uses easting,northing (no latitude-axis swap).
function germanWms(url, layers, attribution, bounds, maxNativeZoom, terrainPane = true) {
 return L.tileLayer.wms(url,{...common,layers,styles:'',format:'image/png',transparent:true,
  version:'1.3.0',crs:L.CRS.EPSG3857,bounds,maxNativeZoom,noWrap:true,attribution,
  pane:terrainPane ? 'terrainPane' : 'backgroundPane',keepBuffer:0});
}
const aerialFl = L.tileLayer('https://geo.api.vlaanderen.be/OMWRGBMRVL/wmts?SERVICE=WMTS&REQUEST=GetTile&VERSION=1.0.0&LAYER=omwrgbmrvl&STYLE=&FORMAT=image/png&TILEMATRIXSET=GoogleMapsVL&TILEMATRIX={z}&TILEROW={y}&TILECOL={x}', {
 ...common,pane:'backgroundPane',maxNativeZoom:21,zIndex:2,bounds:[[50.685,2.53],[51.52,5.92]],
 attribution:'Bron: Luchtopnamen <a href="https://www.vlaanderen.be/datavindplaats/catalogus/wmts-orthofotomozaiek-middenschalig-winteropnamen-kleur-meest-recent-vlaanderen">Digitaal Vlaanderen</a>'
});
const aerialWa = L.tileLayer.wms('https://geoservices.wallonie.be/arcgis/services/IMAGERIE/ORTHO_2023_ETE/MapServer/WMSServer', {
 ...common,pane:'backgroundPane',maxNativeZoom:21,zIndex:1,bounds:[[49.49,2.84],[50.85,6.5]],
 layers:'0',format:'image/png',transparent:true,version:'1.1.1',attribution:'© <a href="https://geoportail.wallonie.be/catalogue/ad55c2ce-62ad-4c3c-b3cf-8fbc270a6b6e.html">SPW · Orthophotos 2023 Été</a> · <a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>'
});
const bases = {
 germany:germanWms('https://sgx.geodatenzentrum.de/wms_basemapde','de_basemapde_web_raster_farbe',deCredit,deBounds,19,false),

 satellite:L.layerGroup([aerialWa,aerialFl]),
 osm:L.tileLayer('https://tile.openstreetmap.be/osmbe/{z}/{x}/{y}.png',{...common,pane:'backgroundPane',maxNativeZoom:18,attribution:'© <a href="https://www.openstreetmap.org/copyright">OpenStreetMap</a> contributors · Tiles generated by <a href="https://www.champs-libres.coop/">Champs-Libres</a>'})
};
const germanViews = {
 nrw:{center:[50.581,6.397],zoom:15,bounds:nrwBounds},
 nrwne:{center:[50.581,6.397],zoom:15,bounds:nrwBounds},
 rlp:{center:[50.2,6.5],zoom:16,bounds:rlpBounds},
 de:{center:[51.16,10.45],zoom:6,bounds:deBounds},
 decomb:{center:[51.16,10.45],zoom:6,bounds:deBounds}
};
function ensureGermanView(name) {
 const view = germanViews[name];
 if(!view || !map._loaded) return;
 const detailed = name === 'nrw' || name === 'nrwne' || name === 'rlp';
 if(!L.latLngBounds(view.bounds).contains(map.getCenter()) || (detailed && map.getZoom() < 10)) {
  map.setView(view.center,view.zoom,{animate:false});
 }
}
function updateSearchArea() {
 $('searchArea').textContent = app.getSearchRegion() === 'de' ? 'Germany' : 'Belgium';
}
let base = null;
for(const layer of [aerialFl,aerialWa,bases.osm,bases.germany]) {
 layer.on('tileerror',() => {
  if(base && (base === layer || (base.hasLayer && base.hasLayer(layer)))) {
   $('backgroundStatus').textContent = 'Background imagery request failed. Try another background or check your connection.';
  }
 });
}

app.setBase = () => {
 if(base) map.removeLayer(base);
 if($('background').value === 'germany') ensureGermanView('de');
 $('backgroundStatus').textContent = '';
 base = bases[$('background').value] || null;
 if(base) base.addTo(map);
 updateSearchArea();
};
function fl(name) {
 return L.tileLayer('https://geo.api.vlaanderen.be/DHMV/wmts?SERVICE=WMTS&REQUEST=GetTile&VERSION=1.0.0&LAYER='+name+'&STYLE=&FORMAT=image/png&TILEMATRIXSET=GoogleMapsVL&TILEMATRIX={z}&TILEROW={y}&TILECOL={x}',{...common,pane:'terrainPane',maxNativeZoom:21,attribution:flCredit,bounds:[[50.68,2.53],[51.52,5.95]]});
}
const terrain = {
 wa:L.tileLayer.wms('https://geoservices.wallonie.be/arcgis/services/RELIEF/WALLONIE_MNT_2021_2022_HILLSHADE/MapServer/WMSServer',{...common,layers:'0',format:'image/png',transparent:true,version:'1.1.1',pane:'terrainPane',tileSize:256,maxNativeZoom:21,attribution:waCredit,bounds:[[49.49,2.84],[50.85,6.5]]}),
 fl:fl('DHMV_II_HILL_25cm'),
 svf:fl('DHMV_II_SVF_25cm'),
 nrw:germanWms('https://www.wms.nrw.de/geobasis/wms_nw_dgm-schummerung','nw_dgm-schummerung_pan',nrwCredit,nrwBounds,19),
 nrwne:germanWms('https://www.wms.nrw.de/geobasis/wms_nw_dgm-schummerung','nw_dgm-schummerung_pan_ne',nrwCredit,nrwBounds,19),
 rlp:germanWms('https://geo4.service24.rlp.de/wms/shade1m.fcgi','rp_shade1m',rlpCredit,rlpBounds,17),
 de:germanWms('https://sgx.geodatenzentrum.de/wms_basemapde_schummerung','de_basemapde_web_raster_hillshade',deCredit,deBounds,14),
 decomb:germanWms('https://sgx.geodatenzentrum.de/wms_basemapde_schummerung','de_basemapde_web_raster_combshade',deCredit,deBounds,14)
};
// Retry only the failed image once; keep Leaflet's normal tile lifecycle.
for(const layer of [aerialFl,aerialWa,bases.osm,bases.germany,...Object.values(terrain)]) {
 const createTile = layer.createTile;
 layer.createTile = function(coords, done) {
  let retried = false;
  return createTile.call(this,coords,(error,tile) => {
   if(error && !retried) {
    retried = true;
    tile.retryTimer = setTimeout(() => {
     if(this._map && tile.isConnected) tile.src = this.getTileUrl(coords);
    },1500);
   } else done(error,tile);
  });
 };
 layer.on('tileunload tileabort',e => clearTimeout(e.tile.retryTimer));
}
const terrainHints = {
 nrw:'North Rhine-Westphalia only · 0.25 m pixels · light from northwest. Try NE lighting to reveal features in another direction.',
 nrwne:'North Rhine-Westphalia only · 0.25 m pixels · light from northeast.',
 rlp:'Rhineland-Palatinate only · 1 m hillshade. Includes the southern Eifel.',
 de:'Germany overview · DGM5 source, approximately 6.4 m rendered pixels. Choose a regional layer for fine features.',
 decomb:'Germany overview · combined hillshade, approximately 6.4 m rendered pixels. Choose a regional layer for fine features.'
};
let active = null, key = '';
const failures = new Set();
function isActive(name) {return key === name || (key === 'auto' && (name === 'wa' || name === 'fl'));}
function terrainStatus() {
 if(!active || app.getTerrains().some(layer => layer.isLoading())) return;
 if(map._loaded && app.getTerrains().every(layer => layer.options.bounds && !map.getBounds().intersects(L.latLngBounds(layer.options.bounds)))) {
  report('Outside this terrain layer’s coverage. Move into the region or choose another layer.'); return;
 }
 const failed = app.getTerrains().some(layer => failures.has(layer));
 report(failed ? 'Some terrain tiles could not load. Try another layer.' : 'Terrain loaded.',!failed);
}
for(const [name,layer] of Object.entries(terrain)) {
 layer.on('loading',() => {
  if(isActive(name)) {failures.delete(layer); report('Loading terrain.');}
 });
 layer.on('tileerror',() => {
  if(isActive(name)) {failures.add(layer); report('Terrain request failed. Try another layer.');}
 });
 layer.on('load',() => {if(isActive(name)) terrainStatus();});
}
app.chooseTerrain = () => {
 let next = $('terrain').value;
 $('terrainHint').textContent = terrainHints[next] || 'Automatic selection covers Belgium only. Select German layers manually; regional coverage ends at state borders.';
 if(next === 'off') next = '';
 if(next === key) return;
 if(active) map.removeLayer(active);
 // A German selection must reveal its coverage and use a compatible background.
 // Keep an explicitly disabled background disabled.
 if(germanViews[next]) {
  ensureGermanView(next);
  if($('background').value !== 'none' && $('background').value !== 'germany') {
   $('background').value = 'germany'; app.setBase();
  }
 }
 key = next; active = key === 'auto' ? L.layerGroup([terrain.wa,terrain.fl]) : terrain[key] || null;
 failures.clear(); updateSearchArea();
 if(!active) {report('LiDAR disabled. Choose a terrain layer.'); if(app.applySplit) app.applySplit(); return;}
 report('Requesting terrain tiles…');
 app.setOpacity(Number($('opacity').value));
 active.addTo(map);
 if(app.applySplit) app.applySplit();
 terrainStatus();
};
app.getSearchRegion = () => germanViews[$('terrain').value] || $('background').value === 'germany' ? 'de' : 'be';
map.on('moveend',terrainStatus);
app.getTerrains = () => !active ? [] : key === 'auto' ? [terrain.wa,terrain.fl] : [active];
app.setOpacity = value => app.getTerrains().forEach(layer => layer.setOpacity(value/100));
})();
